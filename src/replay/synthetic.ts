// Deterministic synthetic day used when no public data has been downloaded.
// It is NOT recorded data and is labelled as synthetic everywhere it appears.

import type { ReplayDataset, ReplayFrame } from './types';

function rng(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s ^ (s >>> 15), 2246822519) + 0x9e3779b9) >>> 0;
    s = Math.imul(s ^ (s >>> 13), 3266489917) >>> 0;
    return ((s ^ (s >>> 16)) >>> 0) / 4294967296;
  };
}

const MIN = 60_000;

/** One synthetic 24 h recording, one frame per minute, starting at 07:00. */
export function syntheticDay(seed = 7): ReplayDataset {
  const r = rng(seed);
  const n = (a: number) => (r() + r() - 1) * a;
  const frames: ReplayFrame[] = [];
  const sleepStart = 16 * 60; // 23:00
  const sleepEnd = sleepStart + 7.5 * 60;
  const exStart = 11 * 60; // 18:00
  const exEnd = exStart + 40;
  const meals = [{ at: 30, carbs: 55 }, { at: 5 * 60 + 15, carbs: 70 }, { at: 11 * 60 + 40, carbs: 80 }]; // 07:30, 12:15, 18:40
  let glucose = 92;
  const nightHrs: number[] = [];
  const counts = { awake: 0, light: 0, deep: 0, rem: 0 };
  const stageAt = (m: number): 'awake' | 'light' | 'deep' | 'rem' => {
    const k = m - sleepStart;
    if (k < 15 || k > 7.5 * 60 - 10) return 'awake';
    const cyc = Math.floor((k - 15) / 90), within = (k - 15) % 90;
    if (within < 10) return 'light';
    if (within < 45) return cyc < 2 ? 'deep' : 'light';
    if (within < 70) return 'light';
    return 'rem';
  };
  const sleptHours = Math.round(((sleepEnd - sleepStart) / 60) * 10) / 10;
  for (let m = 0; m < 24 * 60; m++) {
    const asleep = m >= sleepStart && m < sleepEnd;
    const exercising = m >= exStart && m < exEnd;
    const sinceEx = m >= exEnd ? m - exEnd : m < exStart ? null : 0;
    const lastMeal = [...meals].reverse().find((x) => x.at <= m);
    const mealAgo = lastMeal ? m - lastMeal.at : null;
    const stage = asleep ? stageAt(m) : null;
    let hr = 64 + n(2.5);
    if (asleep) hr = 54 + (stage === 'deep' ? -3 : stage === 'rem' ? 3 : 0) + n(1.5);
    else if (exercising) hr = 142 + n(8);
    else if (sinceEx !== null && sinceEx < 20) hr = 64 + 28 * Math.exp(-sinceEx / 6) + n(2);
    else if (r() < 0.07) hr = 88 + n(6); // short walks around the room
    const walking = !asleep && !exercising && hr > 84;
    let target = asleep ? 86 : 92;
    for (const x of meals) { const d = m - x.at; if (d >= 0) target += x.carbs * 0.55 * (d / 40) * Math.exp(1 - d / 40); }
    glucose += (target - glucose) * 0.25 + n(0.6);
    const f: ReplayFrame = {
      t: m * MIN, hr: Math.round(hr), glucose: Math.round(glucose),
      skinTemp: Math.round((33.4 + (asleep ? 0.3 : 0) + (exercising ? 0.6 : 0) + n(0.1)) * 10) / 10,
      activity: exercising || walking ? 'active' : 'resting',
      quality: exercising || walking ? 'motion' : 'good',
      posture: asleep ? 'lying' : exercising ? 'standing' : 'seated',
      exerciseMinAgo: sinceEx, mealMinAgo: mealAgo, sleepHours: m >= sleepEnd ? sleptHours : null,
      seg: asleep ? 'sleep' : exercising ? 'exercise' : 'day',
    };
    if (m % 30 === 15 && !asleep) { // a cuff reading every 30 minutes
      f.sys = Math.round(118 + n(4) + (sinceEx !== null && sinceEx < 30 ? 12 : 0));
      f.dia = Math.round(76 + n(3) + (sinceEx !== null && sinceEx < 30 ? 4 : 0));
      if (exercising) f.quality = 'motion';
    }
    if (m >= 65 && m < 77) { f.quality = 'poor_fit'; f.hr = Math.round(f.hr! + n(18)); } // loose strap: kept and labelled
    const meal = meals.find((x) => x.at === m);
    if (meal) f.mealCarbsG = meal.carbs;
    if (stage) { counts[stage]++; nightHrs.push(f.hr!); }
    if (m === sleepEnd) {
      const asleepMin = counts.light + counts.deep + counts.rem;
      const sorted = [...nightHrs].sort((a, b) => a - b);
      f.sleep = {
        hours: Math.round((asleepMin / 60) * 10) / 10, efficiencyPct: Math.round((asleepMin / (sleepEnd - sleepStart)) * 100),
        awakeMin: counts.awake, lightMin: counts.light, deepMin: counts.deep, remMin: counts.rem,
        restingHr: sorted[Math.floor(sorted.length * 0.1)] ?? 0,
      };
    }
    frames.push(f);
  }
  return {
    id: 'synthetic', title: 'Synthetic day (generated in the app)', kind: 'synthetic',
    description: 'A 24 hour day generated by the app. Not recorded from a person.',
    attribution: 'Generated by the AstroVitals prototype.', license: 'n/a (generated)',
    limits: 'Shapes are invented for testing the pipeline. They are not physiological reference data.',
    durationMs: 24 * 60 * MIN, frames,
  };
}
