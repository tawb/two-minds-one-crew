import type { StoredContext } from '../readings/types';
// Shared data contract (report §5, §7). Every observation carries ID, subject, metric,
// value, units, measured time, device, quality and origin. Missing values are explicit (value = null).

export type Metric =
  | 'heart_rate' | 'activity' | 'skin_temp' | 'glucose' | 'sleep'
  | 'bp_systolic' | 'bp_diastolic'
  | 'co2' | 'cabin_temp' | 'cabin_rh'
  | 'symptom' | 'mood' | 'stress' | 'fatigue';

export const UNITS: Record<Metric, string> = {
  heart_rate: 'bpm', activity: 'state', skin_temp: '°C', glucose: 'mg/dL', sleep: 'h',
  bp_systolic: 'mmHg', bp_diastolic: 'mmHg', co2: 'ppm', cabin_temp: '°C', cabin_rh: '% RH',
  symptom: 'text', mood: 'score 1–5', stress: 'score 1–5', fatigue: 'score 1–5',
};

export const METRIC_LABEL: Record<Metric, string> = {
  heart_rate: 'Pulse', activity: 'Activity', skin_temp: 'Skin temperature', glucose: 'Sensor glucose',
  sleep: 'Estimated sleep', bp_systolic: 'Blood pressure (systolic)', bp_diastolic: 'Blood pressure (diastolic)',
  co2: 'Cabin CO₂', cabin_temp: 'Cabin temperature', cabin_rh: 'Cabin humidity',
  symptom: 'Symptom report', mood: 'Mood', stress: 'Stress', fatigue: 'Fatigue',
};

/** simulated = generated by the simulator; device = real hardware (unused in this prototype);
 *  manual = typed in; simulated-self-report = automatically generated symptom / well-being entry. */
export type Origin = 'simulated' | 'device' | 'manual' | 'simulated-self-report' | 'replay';
export type Quality = 'good' | 'poor' | 'missing' | 'excluded';

export type MetaValue = string | number | boolean | null;

export interface Obs {
  id: string;
  subjectId: string; // astronaut id (A1..) or cabin module id (M1..)
  metric: Metric;
  value: number | string | null;
  units: string;
  measuredAt: number; // simulated-clock ms
  deviceId: string;
  quality: Quality;
  origin: Origin;
  correctionOf?: string; // link to the original record
  meta?: Record<string, MetaValue>;
  /** Posture, last exercise, last meal and last night's sleep at the time of the reading (absolute times). */
  ctx?: StoredContext;
}

export type Level = 'logged' | 'verify' | 'review' | 'help';
export const LEVEL_LABEL: Record<Level, string> = {
  logged: 'Logged', verify: 'Verify', review: 'Review suggested', help: 'Help requested',
};
export const LEVEL_RANK: Record<Level, number> = { logged: 0, verify: 1, review: 2, help: 3 };

export type AlertKind = 'vital' | 'cabin' | 'sleep' | 'symptom' | 'help';

export interface Alert {
  id: string;
  version: number;
  kind: AlertKind;
  subjectId: string; // astronaut or module
  level: Level;
  title: string;
  lines: string[]; // explanation: observations, times, locations, quality
  evidence: string[]; // observation ids
  contextNote?: string;
  procedure: string; // labelled placeholder, never a real procedure
  createdAt: number;
  updatedAt: number;
  status: 'open' | 'cleared' | 'closed';
  onboardReview: 'none' | 'requested' | 'reviewed';
  groundReply?: { text: string; at: number };
  simulated: boolean;
}

export type DeviceKind = 'band' | 'cuff' | 'patch' | 'cabin';
export type DeviceState = 'ok' | 'disconnected' | 'poor-contact';

export interface Device {
  id: string;
  kind: DeviceKind;
  ownerId: string;
  label: string;
  state: DeviceState;
  since: number;
  battery: number | null; // % ; null = externally powered
  lastValidAt: number | null;
}

export interface DeviceMsg {
  id: string;
  version: number;
  deviceId: string;
  subjectId: string;
  kind: 'disconnected' | 'poor-contact' | 'low-battery' | 'cuff-failed';
  text: string;
  createdAt: number;
  updatedAt: number;
  active: boolean;
}

/** Something that is transmitted to Earth. Alerts/device messages are versioned: id = `${itemId}.v${n}`. */
export interface Rec {
  id: string;
  kind: 'obs' | 'alert' | 'device';
  subjectId: string;
  at: number; // measured / updated time (original timestamp, preserved across retries)
  obs?: Obs;
  alert?: Alert;
  dev?: DeviceMsg;
}

export interface OutboxItem {
  rec: Rec;
  enqueuedAt: number;
  attempts: number;
  sentAt?: number;
  deliverAt?: number;
  ackAt?: number;
  attemptDelivered?: boolean;
}

export interface EarthRec {
  rec: Rec;
  receivedAt: number; // Earth receipt time
}

export type EarthReviewStatus = 'received' | 'under-review' | 'reviewed';
export interface EarthReview { status: EarthReviewStatus; updatedAt: number }

export type CuffPhase = 'idle' | 'inflating' | 'measuring' | 'deflating' | 'completed' | 'failed' | 'cancelled';
export interface CuffState {
  phase: CuffPhase;
  origin: 'scheduled' | 'manual' | null;
  startedAt: number | null;
  endedAt: number | null;
  cycleId: string | null;
  message: string;
  nextScheduled: number;
}

export type Speed = 1 | 10 | 60;
export type McRole = 'ops' | 'surgeon';
